/**
 * Joint-demand tags (catalog follow-up, 2026-08-11).
 *
 * Which joints an exercise places OUTSIZED mechanical demand on — the
 * movements a coach would flag for someone with a grumpy shoulder, elbow,
 * wrist, lower back, hip, knee, or ankle. This is deliberately NOT "which
 * joints are involved" (that would tag everything) and NOT medical advice:
 * it is the practical avoid/swap signal coaches use.
 *
 * An EMPTY array means the row was audited and carries no outsized demand
 * (often the row is itself the joint-friendly swap: floor press, landmine
 * press, reverse lunge, chest-supported rows, hip thrusts). Absence from
 * the map means not yet audited (only C/D-tier rows, by scope).
 *
 * SCOPE: S/A/B tier rows (544), authored per group like tiers and cues;
 * a group in JOINT_DEMAND_COMPLETED_GROUPS must have every S/A/B row
 * present (spec-enforced).
 *
 * CONSUMERS: GET /exercises/:id (detail chips) and pickReplacement —
 * when a user's avoid phrases name a joint ("shoulder", "knee pain"),
 * replacement candidates tagged with that joint are excluded on top of
 * the existing free-text matching. Generation does not read this file.
 */

export type JointId =
  | 'shoulder'
  | 'elbow'
  | 'wrist'
  | 'lower_back'
  | 'hip'
  | 'knee'
  | 'ankle';

export const JOINT_LABELS: Record<JointId, string> = {
  shoulder: 'Shoulders',
  elbow: 'Elbows',
  wrist: 'Wrists',
  lower_back: 'Lower back',
  hip: 'Hips',
  knee: 'Knees',
  ankle: 'Ankles',
};

/**
 * Substrings in a user's avoid phrases that imply a joint. Matched
 * case-insensitively against each phrase. "back" alone is deliberately
 * absent — it names a muscle group, not the lumbar spine.
 */
const JOINT_AVOID_SYNONYMS: [string, JointId][] = [
  ['shoulder', 'shoulder'],
  ['rotator cuff', 'shoulder'],
  ['elbow', 'elbow'],
  ['wrist', 'wrist'],
  ['lower back', 'lower_back'],
  ['low back', 'lower_back'],
  ['lumbar', 'lower_back'],
  ['hip', 'hip'],
  ['knee', 'knee'],
  ['ankle', 'ankle'],
];

/** Joints implied by a user's free-text avoid phrases. */
export function jointsFromAvoidPhrases(phrases: string[]): JointId[] {
  const found = new Set<JointId>();
  for (const phrase of phrases) {
    const p = phrase.toLowerCase();
    for (const [needle, joint] of JOINT_AVOID_SYNONYMS) {
      if (p.includes(needle)) found.add(joint);
    }
  }
  return [...found];
}

